	def _build_page(self, story: list[Any]) -> list[Any]:
		"""Wrap a story in a KeepInFrame so page layouts remain contained."""

		return [KeepInFrame(7.1 * inch, 9.45 * inch, story, mode="shrink")]

	def generate(
		self,
		company_profile: dict,
		scoring_result: ScoringResult,
		llm_analysis: FullAnalysis,
		radar_chart_bytes: bytes,
	) -> bytes:
		"""Generate the complete PDF report as bytes."""

		buffer = BytesIO()
		doc = SimpleDocTemplate(
			buffer,
			pagesize=A4,
			leftMargin=0.55 * inch,
			rightMargin=0.55 * inch,
			topMargin=0.6 * inch,
			bottomMargin=0.65 * inch,
			title="Digital Transformation Maturity Diagnostic Report",
			author="shinkyou_agent (診鏡 Shinkyō Agent)",
			subject="DX maturity diagnostic report",
		)

		story: list[Any] = []
		story.extend(self._build_cover_story(company_profile))
		story.append(PageBreak())
		story.extend(self._build_exec_summary_story(company_profile, scoring_result, llm_analysis, radar_chart_bytes))
		story.append(PageBreak())

		for dimension in DIMENSIONS:
			story.extend(self._build_page(self._build_dimension_story(dimension, scoring_result, llm_analysis)))
			story.append(PageBreak())

		story.extend(self._build_benchmark_story(scoring_result))
		story.append(PageBreak())
		story.extend(self._build_roadmap_story(scoring_result, llm_analysis))
		story.append(PageBreak())
		story.extend(self._build_methodology_story())

		doc.build(story, onFirstPage=self._page_footer, onLaterPages=self._page_footer)
		pdf_bytes = buffer.getvalue()
		buffer.close()
		return pdf_bytes
