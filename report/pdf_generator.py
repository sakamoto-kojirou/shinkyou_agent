	def __init__(self, language: str):
		"""Initialize the generator for a selected output language."""

		normalized = language.strip().lower()
		self.language = normalized if normalized in {"en", "pt", "ja"} else "en"
		if self.language == "ja":
			from reportlab.pdfbase import pdfmetrics
			from reportlab.pdfbase.cidfonts import UnicodeCIDFont

			try:
				pdfmetrics.registerFont(UnicodeCIDFont("HeiseiKakuGo-W5"))
			except Exception:
				self.language = "en"
		self.styles = self._build_styles()
		self.translations = self._build_translations()
		self._font_name = "HeiseiKakuGo-W5" if self.language == "ja" else "Helvetica"

