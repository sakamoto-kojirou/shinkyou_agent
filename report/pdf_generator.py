	def _build_score_table(self, scoring_result: ScoringResult) -> Table:
		"""Build the score summary table for the executive summary page."""

		score_map = self._dimension_score_map(scoring_result)
		header = [
			Paragraph(self._t("dimension"), self.styles["table_header"]),
			Paragraph(self._t("score"), self.styles["table_header"]),
			Paragraph(self._t("weight"), self.styles["table_header"]),
			Paragraph(self._t("weighted"), self.styles["table_header"]),
		]

		rows = [header]
		for dimension in DIMENSIONS:
			item = score_map[dimension.id]
			rows.append(
				[
					Paragraph(get_text(dimension, self.language), self.styles["table_body"]),
					Paragraph(self._format_percent(item["composite_score"]), self.styles["table_body"]),
					Paragraph(f"{item['weight']:.2f}", self.styles["table_body"]),
					Paragraph(self._format_percent(item["weighted_contribution"]), self.styles["table_body"]),
				]
			)

		table = Table(rows, colWidths=[2.55 * inch, 0.8 * inch, 0.75 * inch, 0.95 * inch], repeatRows=1)
		table.setStyle(
			TableStyle(
				[
					("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#163A63")),
					("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
					("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#D0D0D0")),
					("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.whitesmoke, colors.HexColor("#F8F8F8")]),
					("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
					("LEFTPADDING", (0, 0), (-1, -1), 4),
					("RIGHTPADDING", (0, 0), (-1, -1), 4),
					("TOPPADDING", (0, 0), (-1, -1), 4),
					("BOTTOMPADDING", (0, 0), (-1, -1), 4),
				]
			)
		)
		return table

	def _build_radar_image(self, radar_chart_bytes: bytes) -> Image:
		"""Convert radar chart bytes into a ReportLab image."""

		image = Image(BytesIO(radar_chart_bytes))
		image.drawWidth = 3.7 * inch
		image.drawHeight = 3.7 * inch
		return image

	def _build_dimension_score_bar(self, score: float, width: float = 5.8 * inch) -> Drawing:
		"""Build a proportional score bar for one dimension."""

		height = 18
		drawing = Drawing(width, height)
		drawing.add(Rect(0, 0, width, height, fillColor=colors.HexColor("#ECEFF3"), strokeColor=colors.HexColor("#D0D0D0")))
		filled_width = max(0.0, min(width, (score / 4.0) * width))
		drawing.add(Rect(0, 0, filled_width, height, fillColor=colors.HexColor("#1F77B4"), strokeColor=None))
		drawing.add(String(width + 2, 2, f"{score:.2f}/4.00", fontName="Helvetica", fontSize=9, fillColor=colors.HexColor("#444444")))
		return drawing

	def _build_bullet_list(self, items: list[str], style: ParagraphStyle, bullet_type: str = "bullet") -> ListFlowable:
		"""Build a bullet or numbered list from text items."""

		flowables = [ListItem(Paragraph(item, style), leftIndent=8) for item in items if item.strip()]
		return ListFlowable(
			flowables,
			bulletType=bullet_type,
			start="1",
			leftIndent=14,
			bulletFontName=self._font_name,
			bulletFontSize=9,
		)

	def _build_dimension_story(
		self,
		dimension: Dimension,
		scoring_result: ScoringResult,
		llm_analysis: FullAnalysis,
	) -> list[Any]:
		"""Build the content for a single dimension page."""

		score_map = self._dimension_score_map(scoring_result)
		analysis_map = self._dimension_analysis_map(llm_analysis)
		score_item = score_map[dimension.id]
		analysis_item = analysis_map[dimension.id]

		icon_map = {1: "◆", 2: "■", 3: "▲", 4: "●", 5: "✦"}
		header = Paragraph(
			f"{icon_map.get(dimension.id, '•')} {get_text(dimension, self.language)}",
			self.styles["heading"],
		)

		justification = analysis_item["justification"].strip()
		gap_items = analysis_item["gaps"][:3]
		recommendation_items = analysis_item["recommendations"][:3]

		story: list[Any] = [header, Spacer(1, 0.08 * inch)]
		story.append(Paragraph(self._t("score"), self.styles["subheading"]))
		story.append(self._build_dimension_score_bar(score_item["composite_score"]))
		story.append(Spacer(1, 0.12 * inch))
		story.append(Paragraph(self._t("justification"), self.styles["subheading"]))
		story.append(Paragraph(justification, self.styles["body_small"]))
		story.append(Spacer(1, 0.08 * inch))
		story.append(Paragraph(self._t("gaps"), self.styles["subheading"]))
		story.append(self._build_bullet_list(gap_items or ["-"], self.styles["body_small"], bullet_type="bullet"))
		story.append(Spacer(1, 0.08 * inch))
		story.append(Paragraph(self._t("recommendations"), self.styles["subheading"]))
		story.append(self._build_bullet_list(recommendation_items or ["-"], self.styles["body_small"], bullet_type="1"))
		return story

	def _build_benchmark_drawing(self, scoring_result: ScoringResult) -> Drawing:
		"""Build the comparison bar chart for the benchmark page."""

		score_map = self._dimension_score_map(scoring_result)
		company_values = [score_map[dimension.id]["composite_score"] for dimension in DIMENSIONS]
		benchmark_values = [self._benchmark_score(scoring_result, dimension.id) for dimension in DIMENSIONS]
		labels = [get_text(dimension, self.language) for dimension in DIMENSIONS]

		drawing = Drawing(500, 240)
		chart = VerticalBarChart()
		chart.x = 40
		chart.y = 40
		chart.height = 150
		chart.width = 390
		chart.data = [company_values, benchmark_values]
		chart.categoryAxis.categoryNames = labels
		chart.categoryAxis.labels.boxAnchor = "ne"
		chart.categoryAxis.labels.angle = 25
		chart.categoryAxis.labels.fontName = self._font_name
		chart.categoryAxis.labels.fontSize = 7.5
		chart.valueAxis.valueMin = 0
		chart.valueAxis.valueMax = 4
		chart.valueAxis.valueStep = 1
		chart.valueAxis.labels.fontName = "Helvetica"
		chart.valueAxis.labels.fontSize = 8
		chart.bars[0].fillColor = colors.HexColor("#1F77B4")
		chart.bars[1].fillColor = colors.HexColor("#FF7F0E")
		chart.barLabelFormat = "%.2f"
		chart.barLabels.fontName = "Helvetica"
		chart.barLabels.fontSize = 7
		drawing.add(chart)

		drawing.add(Rect(25, 210, 10, 10, fillColor=colors.HexColor("#1F77B4"), strokeColor=None))
		drawing.add(String(40, 210, self._t("legend_your_company"), fontName=self._font_name, fontSize=9))
		drawing.add(Rect(170, 210, 10, 10, fillColor=colors.HexColor("#FF7F0E"), strokeColor=None))
		drawing.add(String(185, 210, self._t("legend_sme_average"), fontName=self._font_name, fontSize=9))
		return drawing

	def _benchmark_interpretation(self, scoring_result: ScoringResult) -> str:
		"""Return a short benchmark interpretation paragraph."""

		score_map = self._dimension_score_map(scoring_result)
		gaps = scoring_result["benchmark_gaps"]
		sorted_dimensions = sorted(DIMENSIONS, key=lambda dimension: gaps.get(dimension.id, 0.0), reverse=True)
		highest_gap_dimension = sorted_dimensions[0]
		lowest_gap_dimension = sorted_dimensions[-1]

		if self.language == "pt":
			return (
				f"A maior lacuna aparece em {get_text(highest_gap_dimension, self.language)}, sugerindo priorização de melhorias estruturais. "
				f"A melhor proximidade com a referência está em {get_text(lowest_gap_dimension, self.language)}."
			)
		if self.language == "ja":
			return (
				f"最も大きいギャップは「{get_text(highest_gap_dimension, self.language)}」であり、構造的な改善を優先する必要があります。 "
				f"ベンチマークへの最も近い観点は「{get_text(lowest_gap_dimension, self.language)}」です。"
			)
		return (
			f"The largest gap appears in {get_text(highest_gap_dimension, self.language)}, indicating a clear priority for structural improvement. "
			f"The closest area to the benchmark is {get_text(lowest_gap_dimension, self.language)}."
		)

	def _collect_priority_actions(self, scoring_result: ScoringResult, llm_analysis: FullAnalysis) -> list[_RoadmapAction]:
		"""Collect the top priority actions from all recommendation lists."""

		analysis_map = self._dimension_analysis_map(llm_analysis)
		gaps = scoring_result["benchmark_gaps"]
		candidates: list[_RoadmapAction] = []
		seen: set[str] = set()

		for dimension in sorted(DIMENSIONS, key=lambda item: gaps.get(item.id, 0.0), reverse=True):
			analysis = analysis_map.get(dimension.id)
			if analysis is None:
				continue
			recommendations = analysis.get("recommendations", [])[:3]
			for index, recommendation in enumerate(recommendations):
				recommendation_text = recommendation.strip()
				normalized = recommendation_text.lower()
				if not recommendation_text or normalized in seen:
					continue
				seen.add(normalized)
				gap = float(gaps.get(dimension.id, 0.0))
				if gap >= 0.8:
					impact = {"en": "High", "pt": "Alto", "ja": "高"}[self.language]
				elif gap >= 0.4:
					impact = {"en": "Moderate", "pt": "Moderado", "ja": "中"}[self.language]
				else:
					impact = {"en": "Quick win", "pt": "Ganho rápido", "ja": "短期成果"}[self.language]

				if len(candidates) == 0:
					timeline = {"en": "Days 1-15", "pt": "Dias 1-15", "ja": "1〜15日"}[self.language]
				elif len(candidates) == 1:
					timeline = {"en": "Days 16-30", "pt": "Dias 16-30", "ja": "16〜30日"}[self.language]
				elif len(candidates) == 2:
					timeline = {"en": "Days 31-45", "pt": "Dias 31-45", "ja": "31〜45日"}[self.language]
				elif len(candidates) == 3:
					timeline = {"en": "Days 46-60", "pt": "Dias 46-60", "ja": "46〜60日"}[self.language]
				else:
					timeline = {"en": "Days 61-90", "pt": "Dias 61-90", "ja": "61〜90日"}[self.language]

				candidates.append(
					_RoadmapAction(
						action=recommendation_text,
						dimension=get_text(dimension, self.language),
						expected_impact=impact,
						timeline=timeline,
						priority=gap + (0.1 * (3 - index)),
					)
				)
				if len(candidates) >= 5:
					return candidates

		while len(candidates) < 5:
			filler_index = len(candidates) % len(DIMENSIONS)
			dimension = DIMENSIONS[filler_index]
			fallback_text = {
				"en": "Establish a measurable improvement cycle and assign ownership.",
				"pt": "Estabeleça um ciclo de melhoria mensurável e atribua responsabilidade.",
				"ja": "測定可能な改善サイクルを設定し、責任者を明確にしてください。",
			}[self.language]
			candidates.append(
				_RoadmapAction(
					action=fallback_text,
					dimension=get_text(dimension, self.language),
					expected_impact={"en": "Moderate", "pt": "Moderado", "ja": "中"}[self.language],
					timeline={"en": "Days 61-90", "pt": "Dias 61-90", "ja": "61〜90日"}[self.language],
					priority=0.0,
				)
			)

		return candidates[:5]

	def _build_roadmap_table(self, scoring_result: ScoringResult, llm_analysis: FullAnalysis) -> Table:
		"""Build the 90-day action roadmap table."""

		actions = self._collect_priority_actions(scoring_result, llm_analysis)
		header = [
			Paragraph(self._t("action"), self.styles["table_header"]),
			Paragraph(self._t("dimension"), self.styles["table_header"]),
			Paragraph(self._t("expected_impact"), self.styles["table_header"]),
			Paragraph(self._t("timeline"), self.styles["table_header"]),
		]
		rows = [header]
		for action in actions:
			rows.append(
				[
					Paragraph(action.action, self.styles["table_body"]),
					Paragraph(action.dimension, self.styles["table_body"]),
					Paragraph(action.expected_impact, self.styles["table_body"]),
					Paragraph(action.timeline, self.styles["table_body"]),
				]
			)

		table = Table(rows, colWidths=[2.85 * inch, 1.35 * inch, 1.0 * inch, 0.9 * inch], repeatRows=1)
		table.setStyle(
			TableStyle(
				[
					("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#163A63")),
					("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
					("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#D0D0D0")),
					("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.whitesmoke, colors.HexColor("#F8F8F8")]),
					("VALIGN", (0, 0), (-1, -1), "TOP"),
					("LEFTPADDING", (0, 0), (-1, -1), 4),
					("RIGHTPADDING", (0, 0), (-1, -1), 4),
					("TOPPADDING", (0, 0), (-1, -1), 4),
					("BOTTOMPADDING", (0, 0), (-1, -1), 4),
				]
			)
		)
		return table

