	def _t(self, key: str) -> str:
		"""Return a localized string for the current report language."""

		return self.translations[self.language][key]

	def _page_footer(self, canvas: Any, doc: Any) -> None:
		"""Draw the footer on each page."""

		canvas.saveState()
		canvas.setStrokeColor(colors.HexColor("#D0D0D0"))
		canvas.line(doc.leftMargin, 34, doc.pagesize[0] - doc.rightMargin, 34)
		canvas.setFont("Helvetica", 8)
		canvas.setFillColor(colors.HexColor("#6B6B6B"))
		canvas.drawCentredString(
			doc.pagesize[0] / 2,
			22,
			self._t("generated_by"),
		)
		canvas.restoreState()

	def _company_name(self, company_profile: dict) -> str:
		"""Return a display name for the company."""

		company_name = company_profile.get("company_name")
		if isinstance(company_name, str) and company_name.strip():
			return company_name.strip()
		return self._t("your_company")

	def _format_percent(self, value: float) -> str:
		"""Format a numeric value as a score with one decimal place."""

		return f"{value:.2f}"

	def _maturity_badge_color(self, level: int) -> colors.Color:
		"""Return the badge color for a maturity level."""

		if level <= 1:
			return colors.HexColor("#C0392B")
		if level == 2:
			return colors.HexColor("#E67E22")
		if level == 3:
			return colors.HexColor("#F1C40F")
		return colors.HexColor("#2E8B57")

	def _dimension_analysis_map(self, llm_analysis: FullAnalysis) -> dict[int, dict[str, Any]]:
		"""Map dimension identifiers to analysis payloads."""

		return {analysis["dimension_id"]: analysis for analysis in llm_analysis["dimensions"]}

	def _dimension_score_map(self, scoring_result: ScoringResult) -> dict[int, dict[str, Any]]:
		"""Map dimension identifiers to scoring payloads."""

		return {item["dimension_id"]: item for item in scoring_result["dimension_scores"]}

	def _benchmark_score(self, scoring_result: ScoringResult, dimension_id: int) -> float:
		"""Reconstruct the benchmark average from the score gap and company score."""

		score_map = self._dimension_score_map(scoring_result)
		score_item = score_map.get(dimension_id)
		if score_item is None:
			return 0.0
		return float(score_item["composite_score"]) + float(scoring_result["benchmark_gaps"].get(dimension_id, 0.0))

	def _build_cover_story(self, company_profile: dict) -> list[Any]:
		"""Build the cover page content."""

		story: list[Any] = []
		story.append(Spacer(1, 0.65 * inch))
		story.append(Paragraph(self._t("report_title"), self.styles["title"]))
		story.append(Spacer(1, 0.12 * inch))
		story.append(Paragraph(self._t("subtitle"), self.styles["subtitle"]))
		story.append(Spacer(1, 0.8 * inch))
		story.append(Paragraph(self._company_name(company_profile), self.styles["heading"]))
		story.append(Spacer(1, 0.12 * inch))
		story.append(
			Paragraph(
				f"{self._t('generated_on')}: {datetime.now().strftime('%Y-%m-%d')}",
				self.styles["body"],
			)
		)
		story.append(Spacer(1, 0.12 * inch))
		story.append(Paragraph(self._t("based_on"), self.styles["body"]))
		story.append(Spacer(1, 0.8 * inch))
		story.append(Paragraph(self._t("generated_by"), self.styles["subtitle"]))
		return story

